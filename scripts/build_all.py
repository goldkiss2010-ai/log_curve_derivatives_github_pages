def junction_range(c, j):
    x = float(j["value"])
    ax = abs(x)
    if ax < 1e-12: span = 0.035
    elif ax < 0.002: span = max(ax * 0.85, 0.0007)
    elif ax < 0.05: span = max(ax * 0.7, 0.008)
    else: span = ax * 0.55
    lo, hi = x - span, x + span
    if c["model"] == "logc4":
        safe_lo = -64.0 / c["params"]["a"] + 1e-8
        lo = max(lo, safe_lo)
    if c["model"] == "nlog":
        lo = max(lo, -0.00749)
    return lo, hi


def make_junction_triptych(c, j, out_svg, out_png=None, compact=False):
    lo, hi = junction_range(c, j)
    x = np.linspace(lo, hi, 700)
    join = float(j["value"])
    fig, axes = plt.subplots(1, 3, figsize=(9.3, 2.8) if compact else (10.5, 3.2))
    funcs = [cm.encode, cm.d1, cm.d2]
    titles = ["value", "first derivative", "second derivative"]
    ylabs = ["f(r)", "f'(r)", "f''(r)"]
    for ax, fun, title, yl in zip(axes, funcs, titles, ylabs):
        ax.plot(x, fun(c, x), linewidth=1.5)
        ax.axvline(join, linestyle="--", linewidth=.9)
        ax.set_title(title, fontsize=9); ax.set_xlabel("r", fontsize=8); ax.set_ylabel(yl, fontsize=8)
        ax.tick_params(labelsize=7); ax.grid(True, alpha=.22)
    fig.suptitle(f"{c['name']} — {j.get('label', j['id'])} at {join:.6g}", fontsize=11, y=1.01)
    fig.tight_layout()
    fig.savefig(out_svg, bbox_inches="tight")
    if out_png:
        fig.savefig(out_png, dpi=170, bbox_inches="tight")
    plt.close(fig)


def svg_inner(path):
    txt = Path(path).read_text(encoding="utf-8")
    m = re.search(r"(<svg[\s\S]*</svg>)", txt)
    return m.group(1) if m else txt


