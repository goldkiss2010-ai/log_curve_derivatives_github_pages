def source_citation(c):
    return "; ".join("@" + key for key in c.get("sources", []))


def markdown_table(headers, rows, aligns=None):
    def esc(v):
        return str(v).replace("|", "\\|").replace("\n", " ")
    lines = ["| " + " | ".join(esc(h) for h in headers) + " |"]
    if aligns is None:
        aligns = ["---"] * len(headers)
    lines.append("| " + " | ".join(aligns) + " |")
    for row in rows:
        lines.append("| " + " | ".join(esc(v) for v in row) + " |")
    return "\n".join(lines) + "\n"


def fmt_num(x, digits=6):
    if x is None or not np.isfinite(x):
        return ""
    if abs(x) >= 1e4 or (abs(x) > 0 and abs(x) < 1e-5):
        return f"{x:.3e}"
    return f"{x:.{digits}g}"


def generate_bib():
    blocks = []
    for key, s in SOURCES.items():
        typ = s.get("type", "techreport")
        entry = "misc" if typ == "misc" else "techreport"
        author = s.get("author", s.get("organization", ""))
        if " and " in author:
            bib_author = "{" + author + "}"
        else:
            bib_author = "{{" + author + "}}"
        fields = [("author", bib_author), ("title", "{" + s["title"] + "}")]
        if entry == "techreport" and s.get("organization"):
            fields.append(("institution", "{" + s["organization"] + "}"))
        if s.get("year") is not None:
            fields.append(("year", str(s["year"])))
        if s.get("month"):
            fields.append(("month", "{" + str(s["month"]) + "}"))
        if s.get("url"):
            fields.append(("url", "{" + s["url"] + "}"))
        if s.get("note"):
            fields.append(("note", "{" + s["note"] + "}"))
        lines = [f"@{entry}{{{key},"]
        for i, (k, v) in enumerate(fields):
            comma = "," if i < len(fields) - 1 else ""
            lines.append(f"  {k:<11} = {v}{comma}")
        lines.append("}")
        blocks.append("\n".join(lines))
    (ROOT / "references.bib").write_text("\n\n".join(blocks) + "\n", encoding="utf-8")


def generate_fragments(summary_df, junction_df):
    camera_lines = []
    for c in CAMERAS:
        cites = source_citation(c)
        camera_lines.append(f"- {c['name']} [{cites}]" if cites else f"- {c['name']}")
    (GENERATED / "camera_curves.qmd").write_text("\n".join(camera_lines) + "\n", encoding="utf-8")

    headers = ["Curve", "y(18%)", "1023×y", "1023×dy/dstop at 18%", "d²y/dstop² at 18%"]
    rows = []
    for _, r in summary_df.iterrows():
        rows.append([
            r["curve"], fmt_num(r["y_18pct"]), fmt_num(r["code_1023"]),
            fmt_num(r["code_per_stop_1023"]), fmt_num(r["d2_stop_18pct"]),
        ])
    (GENERATED / "summary_table.qmd").write_text(markdown_table(headers, rows, [":---", "---:", "---:", "---:", "---:"]), encoding="utf-8")

    headers = ["Curve", "Junction", "Join", "Domain", "Lower / left branch", "Upper / right branch", "C0", "C1", "C2"]
    rows = []
    for _, r in junction_df.iterrows():
        rows.append([
            r["curve"], r["junction_label"], fmt_num(r["join"], 7), r["domain"],
            r["lower_branch"], r["upper_branch"], r["C0"], r["C1"], r["C2"],
        ])
    # Smooth reference rows without a junction.
    for c in REFERENCES:
        if not c.get("junctions"):
            rows.append([c["name"], "—", "", "none", c["branches"]["low"], c["branches"]["high"],
                         "smooth/no piecewise join", "smooth/no piecewise join", "smooth/no piecewise join"])
    (GENERATED / "junction_table.qmd").write_text(markdown_table(headers, rows, [":---", ":---", "---:", ":---", ":---", ":---", ":---", ":---", ":---"]), encoding="utf-8")

    # Direct primary-source index, useful even when the article is used simply as a white-paper link collection.
    seen = set()
    source_rows = []
    for c in CAMERAS:
        for key in c.get("sources", []):
            if key in seen:
                continue
            seen.add(key)
            s = SOURCES[key]
            url = s.get("url")
            title = s["title"]
            link = f"[{title}]({url})" if url else title
            source_rows.append([s.get("organization", s.get("author", "")), link, str(s.get("year", ""))])
    (GENERATED / "primary_sources.qmd").write_text(
        markdown_table(["Organization", "Specification / white paper", "Year"], source_rows, [":---", ":---", "---:"]), encoding="utf-8")


def overview_data():
    rmin = float(CONFIG.get("scene_min", 1e-5))
    rmax = float(CONFIG.get("scene_max", 16.0))
    r = np.unique(np.r_[np.geomspace(rmin, 0.02, 900), np.geomspace(0.02, rmax, 1800)])
    stops = np.linspace(float(CONFIG.get("stop_min", -12.0)), float(CONFIG.get("stop_max", 10.0)), 1800)
    rs = GRAY * (2.0**stops)
    return r, stops, rs


def save_overview_plot(filename, domain, metric):
    r, stops, rs = overview_data()
    fig, ax = plt.subplots(figsize=(10, 6.5))
    for c in CAMERAS:
        if domain == "scene":
            x = r
            if metric == "y": y = cm.encode(c, r)
            elif metric == "d1": y = cm.d1(c, r)
            else: y = cm.d2(c, r)
        else:
            x = stops
            if metric == "y": y = cm.encode(c, rs)
            elif metric == "d1": y = cm.g1_stop(c, rs)
            else: y = cm.g2_stop(c, rs)
        ax.plot(x, y, label=c["name"])
    if domain == "scene":
        ax.set_xscale("log")
        ax.set_xlabel("Reflectance-like scene-linear input r (18% gray = 0.18)")
        if metric == "y":
            ax.set_ylabel("Normalized encoded output"); ax.set_title("Published camera log curves — common reflectance-like axis")
        elif metric == "d1":
            ax.set_yscale("log"); ax.set_ylabel("First derivative f'(r)"); ax.set_title("First derivative in scene-linear domain")
        else:
            ax.set_yscale("symlog", linthresh=1e-2); ax.set_ylabel("Second derivative f''(r)"); ax.set_title("Second derivative in scene-linear domain (symlog y-scale)")
    else:
        ax.set_xlabel("Stops from 18% gray")
        if metric == "y":
            ax.set_ylabel("Normalized encoded output"); ax.set_title("Published camera log curves — stop domain")
        elif metric == "d1":
            ax.set_ylabel("g'(s): normalized output per stop"); ax.set_title("Code allocation per stop")
        else:
            ax.set_ylabel("g''(s): change of allocation per stop²"); ax.set_title("Second derivative in stop domain")
    ax.grid(True, which="both", alpha=0.25)
    ax.legend(frameon=False, fontsize=7, ncol=3)
    fig.tight_layout()
    fig.savefig(FIG_OV / (filename + ".svg"))
    fig.savefig(FIG_OV / (filename + ".png"), dpi=180)
    plt.close(fig)


